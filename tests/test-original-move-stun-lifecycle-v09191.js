'use strict';
const fs=require('fs');
const path=require('path');
const {WAInterpreter}=require('../wa-script-interpreter-core.js');
const {WAGameStateAdapter}=require('../wa-game-state-adapter.js');
const asts=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/original-card-script-asts.json'),'utf8'));
const scripts=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/original-card-scripts.json'),'utf8'));
const app=fs.readFileSync(path.join(__dirname,'../app.js'),'utf8');
const checks=[];
const ok=(name,pass,detail='')=>checks.push({name,pass:!!pass,detail});
const player={key:'player',name:'Player',hp:70,maxHp:70,momentum:{Attitude:0,Agility:0,Knowledge:0,Strength:0,Strike:0,Technical:0},hand:[],deck:[],discard:[],inPlay:[],zoneDamage:{Head:0,Body:0,Arm:0,Leg:0}};
const cpu={key:'cpu',name:'CPU',hp:70,maxHp:70,momentum:{Attitude:0,Agility:0,Knowledge:0,Strength:0,Strike:0,Technical:0},hand:[],deck:[],discard:[],inPlay:[],zoneDamage:{Head:0,Body:0,Arm:0,Leg:0}};
const state={round:3,control:'cpu',player,cpu};
const tough={name:'Tough Guy',sourceFile:'ToughGuy.gac',owner:player,playedBy:player};
player.inPlay.push(tough);
const adapter=new WAGameStateAdapter(state,{actor:player,target:player,thisPage:tough,pageCatalog:new Map()});
const interpreter=new WAInterpreter(adapter.asFunctions(),{maxSteps:10000});
const result=interpreter.run(asts['ToughGuy.gac'].Can_Stun,{'#superstar':player,'#target':player,'#this':tough,'#incontrol':cpu});
ok('Recovered Tough Guy vetoes one Stun',result?.result===false,JSON.stringify(result));
ok('Recovered Tough Guy leaves play after preventing Stun',!player.inPlay.includes(tough),String(player.inPlay.length));
ok('Recovered Begin_Move handler count',Object.values(scripts).filter(x=>x&&x.Begin_Move).length===11);
ok('Recovered End_Move handler count',Object.values(scripts).filter(x=>x&&x.End_Move).length===1);
ok('Recovered Can_Stun handler count',Object.values(scripts).filter(x=>x&&x.Can_Stun).length===3);
ok('Recovered Stunned handler count',Object.values(scripts).filter(x=>x&&x.Stunned).length===16);
ok('Begin_Move is audited before response window',app.includes('const beginMoveRows=dispatchOriginalEvent(\'Begin_Move\''));
ok('End_Move is dispatched after successful resolution',app.includes("const endMoveRows=dispatchOriginalEvent('End_Move'"));
ok('Printed and attached Stuns use shared certified lifecycle',app.includes('if(c.attachedSpecialStun)applyCertifiedStun')&&app.includes('applyCertifiedStun(dKey,c,Number(c.stun)||0,k)'));
ok('Connected move control uses certified Control_Changed path',app.includes("changeControlCertified(k,'after the connected move')"));
ok('Move lifecycle audit exposed in live state',app.includes('lastOriginalMoveLifecycleAudit'));
const failed=checks.filter(x=>!x.pass);
const report={version:'v0.9.191',passed:checks.length-failed.length,total:checks.length,failed,checks};
console.log(JSON.stringify(report,null,2));
if(failed.length)process.exit(1);
