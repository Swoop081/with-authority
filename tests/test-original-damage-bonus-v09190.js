'use strict';
const fs=require('fs');
const path=require('path');
const {WAInterpreter}=require('../wa-script-interpreter-core.js');
const {WAGameStateAdapter}=require('../wa-game-state-adapter.js');
const asts=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/original-card-script-asts.json'),'utf8'));
const app=fs.readFileSync(path.join(__dirname,'../app.js'),'utf8');
const scripts=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/original-card-scripts.json'),'utf8'));
const checks=[];
const ok=(name,pass,detail='')=>checks.push({name,pass:!!pass,detail});
const player={key:'player',name:'Player',hp:70,maxHp:70,momentum:{Attitude:0,Agility:0,Knowledge:0,Strength:2,Strike:0,Technical:0},hand:[],deck:[],discard:[],inPlay:[],connectedMoves:[],zoneDamage:{Head:0,Body:0,Arm:0,Leg:0}};
const cpu={key:'cpu',name:'CPU',hp:70,maxHp:70,momentum:{Attitude:0,Agility:0,Knowledge:0,Strength:0,Strike:0,Technical:0},hand:[],deck:[],discard:[],inPlay:[],connectedMoves:[],zoneDamage:{Head:0,Body:0,Arm:0,Leg:0}};
const state={round:3,control:'player',player,cpu};
const persistent={name:'Big and Nasty',sourceFile:'BigandNastyEX1.gac',owner:player};
const move={name:'Test Strength Move',sourceFile:'Test.gac',cardClass:'Move',method:'Strength',damage:4,owner:player,playedBy:player};
player.inPlay.push(persistent);
const adapter=new WAGameStateAdapter(state,{actor:player,target:cpu,thisPage:persistent,pageCatalog:new Map()});
const interpreter=new WAInterpreter(adapter.asFunctions(),{maxSteps:10000});
interpreter.run(asts['BigandNastyEX1.gac'].Damage_Bonus,{'#superstar':player,'#target':cpu,'#this':persistent,'#move':move});
ok('WAStringGetValue exposes printed Method',adapter.WAStringGetValue(move,'Method')==='Strength',adapter.WAStringGetValue(move,'Method'));
ok('Recovered Big and Nasty adds +2 Damage_Bonus',Number(move.waValues?.Damage_Bonus)===2,JSON.stringify(move.waValues||{}));
move.waValues.Damage_Bonus=0;
interpreter.run(asts['BigandNastyEX1.gac'].Damage_Bonus,{'#superstar':player,'#target':cpu,'#this':persistent,'#move':move});
ok('Damage bonus is repeatable after per-resolution reset',Number(move.waValues?.Damage_Bonus)===2,JSON.stringify(move.waValues||{}));
ok('Recovered Damage_Bonus handler count',Object.values(scripts).filter(x=>x&&x.Damage_Bonus).length===170);
ok('Live attack consumes original dynamic bonus',app.includes('originalDynamicDamageBonus')&&app.includes("c.waValues.Damage_Bonus=0"));
ok('Original damage audit exposed',app.includes('getOriginalDamageAudit'));
ok('Confirmed duplicate Big and Nasty fallback removed',!app.includes("e.bigAndNasty)&&c.method===\'Strength\'"));
ok('Confirmed duplicate Table damage fallback removed',!app.includes("const tableOwner=['player','cpu']"));
ok('Confirmed duplicate Bounce Off The Ropes fallback removed',!app.includes('e.bounceOffRopes)&&(mods.includes'));
ok('Move_Connected dispatch includes persistent participants',app.includes("dispatchOriginalEvent('Move_Connected',k,c"));

const failed=checks.filter(x=>!x.pass);
console.log(JSON.stringify({version:'v0.9.190',passed:checks.length-failed.length,total:checks.length,failed,checks},null,2));
if(failed.length)process.exit(1);
