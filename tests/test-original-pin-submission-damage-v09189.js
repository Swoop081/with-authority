'use strict';
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const scripts=JSON.parse(fs.readFileSync(path.join(root,'data/original-card-scripts.json'),'utf8'));
const count=event=>Object.values(scripts).filter(x=>x&&Object.prototype.hasOwnProperty.call(x,event)).length;
const checks=[];
const ok=(name,pass,detail='')=>checks.push({name,pass:!!pass,detail});
ok('Recovered Attempt_Pin handlers',count('Attempt_Pin')===5,`found ${count('Attempt_Pin')}`);
ok('Recovered Can_Pin handlers',count('Can_Pin')===2,`found ${count('Can_Pin')}`);
ok('Recovered Can_Submit handlers',count('Can_Submit')===3,`found ${count('Can_Submit')}`);
ok('Recovered Prevent_Damage handlers',count('Prevent_Damage')===1,`found ${count('Prevent_Damage')}`);
ok('Recovered Prevent_Submission_Damage handlers',count('Prevent_Submission_Damage')===1,`found ${count('Prevent_Submission_Damage')}`);
ok('Normal damage consults recovered Prevent_Damage gate',app.includes("originalBooleanGate('Prevent_Damage',k,c"));
ok('Submission upkeep consults recovered prevention gate',app.includes("originalBooleanGate('Prevent_Submission_Damage',k,h.card"));
ok('Submission creation consults Can_Submit',app.includes("originalBooleanGate('Can_Submit',k,c"));
ok('Pin attempt consults Can_Pin and Attempt_Pin',app.includes("originalBooleanGate('Can_Pin',k,null")&&app.includes("originalBooleanGate('Attempt_Pin',k,null"));
ok('Structured finish recorder exists',app.includes('function recordMatchFinish'));
ok('Victory end records structured metadata',app.includes("recordMatchFinish({winner:winnerKey,finishType"));
ok('Turn-limit draw records structured metadata',app.includes("recordMatchFinish({winner:null,finishType:'draw'"));
ok('Finished matches release busy lock',/recordMatchFinish\([\s\S]{0,500}state\.busy=false/.test(app));
const failed=checks.filter(x=>!x.pass);
console.log(JSON.stringify({version:'v0.9.189',passed:checks.length-failed.length,total:checks.length,failed,checks},null,2));
if(failed.length)process.exit(1);
